/**
 * 带有动态模式替换的翻译器
 */
export function translatePattern(text: string): string | null {
  if (text.startsWith("Open project ")) {
    return `打开项目 ${text.slice("Open project ".length)}`;
  }
  if (text.endsWith(" chats · now")) {
    const num = text.replace(" chats · now", "").replace(" chat · now", "");
    return `${num} 个对话 · 刚刚`;
  }
  const chatMatch = text.match(/^(\d+) chats? · (.+)$/);
  if (chatMatch) {
    return `${chatMatch[1]} 个对话 · ${chatMatch[2]}`;
  }
  const minAgoMatch = text.match(/^(\d+) minutes? ago$/);
  if (minAgoMatch) {
    return `${minAgoMatch[1]} 分钟前`;
  }
  const hourAgoMatch = text.match(/^(\d+) hours? ago$/);
  if (hourAgoMatch) {
    return `${hourAgoMatch[1]} 小时前`;
  }
  const dayAgoMatch = text.match(/^(\d+) days? ago$/);
  if (dayAgoMatch) {
    return `${dayAgoMatch[1]} 天前`;
  }
  const weekAgoMatch = text.match(/^(\d+) weeks? ago$/);
  if (weekAgoMatch) {
    return `${weekAgoMatch[1]} 周前`;
  }
  return null;
}
